"""LinuxCNC post (RS274NGC). Supports the A rotary axis and real tool changes.

Tool numbers come from `Tool.number` when set, otherwise tools are numbered in
order of first use. LinuxCNC applies the tool length offset with G43.

Runs of feed moves are written as G2/G3 arcs where an arc fits them within
`arc_tolerance` (see camcore/arcfit.py); arcs=False keeps everything as G1.
Rotary (A-axis) toolpaths that cut while A turns stay linear, in G93 inverse
time. Indexed toolpaths (A only turns in rapids that move nothing else) are
ordinary 3-axis work in G94 with arcs, and their A positions are always written.
"""
from __future__ import annotations

import math

from ..arcfit import fit_run
from ..toolpath import Toolpath
from .base import PostProcessor


class LinuxCncPost(PostProcessor):
    name = "linuxcnc"
    decimals = 4
    supports_a_axis = True
    path_tolerance = 0.01   # G64 P: blending tolerance in mm

    def __init__(self, atc_prefetch: bool = True, arcs: bool = True, arc_tolerance: float = 0.01):
        # With a carousel/rack ATC, issuing the next T word right after M6 lets
        # the changer stage the next tool while this one cuts.
        self.atc_prefetch = atc_prefetch
        if arc_tolerance <= 0:
            raise ValueError("arc_tolerance must be > 0")
        self.arcs, self.arc_tolerance = arcs, arc_tolerance
        self._numbers: dict = {}
        self._last_tool = None
        self._upcoming: list = []

    def header(self) -> list[str]:
        return ["%", "(generated by camcore)",
                "G21 G90 G17 G40 G49 G80 G94",
                f"G64 P{self.fmt(self.path_tolerance)}"]

    def footer(self) -> list[str]:
        return ["M5 M9", "G53 G0 Z0", "M2", "%"]

    def tool_number(self, tool) -> int:
        n = getattr(tool, "number", None)
        if n:
            return n
        return self._numbers.setdefault(tool, len(self._numbers) + 1)

    def tool_change(self, tp: Toolpath) -> list[str]:
        out = [f"({tp.name})"]
        if tp.tool != self._last_tool:
            n = self.tool_number(tp.tool)
            out += ["M5", "G53 G0 Z0", f"T{n} M6 ({tp.tool.name} D{self.fmt(tp.tool.diameter)})", f"G43 H{n}"]
            self._last_tool = tp.tool
            nxt = next((t for t in self._upcoming if t != tp.tool), None)
            if self.atc_prefetch and nxt is not None:
                out.append(f"T{self.tool_number(nxt)} (stage next tool)")
        if self._upcoming:
            self._upcoming.pop(0)
        out.append(f"M3 S{int(tp.spindle_rpm)}")
        return out

    def emit(self, paths):
        self._numbers, self._last_tool = {}, None
        self._upcoming = [tp.tool for tp in paths]
        for t in self._upcoming:          # number tools in order of first use
            self.tool_number(t)
        return super().emit(paths)

    @staticmethod
    def indexed(tp: Toolpath) -> bool:
        """A turns only in rapids that move no other axis (indexed 3+1)."""
        return all(m.a is None or (m.kind == "rapid" and m.x is None and m.y is None and m.z is None)
                   for m in tp.moves)

    def moves(self, tp: Toolpath) -> list[str]:
        if tp.uses_a_axis() and not self.indexed(tp):
            return ["G93 (inverse-time feed for rotary moves)"] + self._inverse_time_moves(tp) + ["G94"]
        if not self.arcs:
            return super().moves(tp)
        return self._arc_moves(tp)

    def _arc_moves(self, tp: Toolpath) -> list[str]:
        q = 10 ** -self.decimals
        out, emitted, last_feed = [], {}, None
        pos = {"x": None, "y": None, "z": None}

        def words(target):
            ws = []
            for k in ("x", "y", "z"):
                v = target.get(k)
                if v is None:
                    continue
                v = round(v, self.decimals)
                if emitted.get(k) is None or abs(emitted[k] - v) >= q:
                    ws.append(f"{k.upper()}{self.fmt(v)}")
                    emitted[k] = v
            return ws

        def feed_word(f):
            nonlocal last_feed
            if f is None or f == last_feed:
                return ""
            last_feed = f
            return f" F{self.fmt(f)}"

        moves, k = tp.moves, 0
        while k < len(moves):
            m = moves[k]
            if m.kind == "rapid" or None in pos.values():
                target = {a: getattr(m, a) for a in "xyz"}
                ws = words(target)
                if m.a is not None:             # an index turn: always written, it is the face
                    ws.append(f"A{self.fmt(m.a)}")
                pos.update({a: v for a, v in target.items() if v is not None})
                if ws:
                    out.append(("G0 " if m.kind == "rapid" else "G1 ") + " ".join(ws)
                               + (feed_word(m.feed) if m.kind == "feed" else ""))
                k += 1
                continue
            # a run of feed moves at one feed rate, starting from the current position
            f = m.feed if m.feed is not None else last_feed
            pts = [(pos["x"], pos["y"], pos["z"])]
            while k < len(moves) and moves[k].kind == "feed" and moves[k].feed in (None, f):
                mk = moves[k]
                pos.update({a: getattr(mk, a) for a in "xyz" if getattr(mk, a) is not None})
                pts.append((pos["x"], pos["y"], pos["z"]))
                k += 1
            for piece in fit_run(pts, self.arc_tolerance):
                if piece[0] == "arc":
                    _, i, j, centre, cw = piece
                    line = self._arc_line(pts[i], pts[j], centre, cw, words)
                    if line:
                        out.append(line + feed_word(f))
                        continue
                    ends = range(i + 1, j + 1)          # rounding broke the arc: keep the lines
                else:
                    ends = [piece[1]]
                for e in ends:
                    ws = words(dict(zip("xyz", pts[e])))
                    if ws:
                        out.append("G1 " + " ".join(ws) + feed_word(f))
        return out

    def _arc_line(self, start, end, centre, cw, words):
        """G2/G3 line with the centre moved onto the perpendicular bisector of the
        *rounded* start and end, so both radii agree to well under a micron."""
        sx, sy = (round(v, self.decimals) for v in start[:2])
        ex, ey = (round(v, self.decimals) for v in end[:2])
        mx, my = (sx + ex) / 2, (sy + ey) / 2
        ux, uy = -(ey - sy), ex - sx
        n = math.hypot(ux, uy)
        if n < 1e-9:
            return None
        ux, uy = ux / n, uy / n
        t = (centre[0] - mx) * ux + (centre[1] - my) * uy
        cx, cy = mx + t * ux, my + t * uy
        if math.hypot(cx - centre[0], cy - centre[1]) > self.arc_tolerance:
            return None
        i, j = round(cx - sx, self.decimals), round(cy - sy, self.decimals)
        ws = words(dict(zip("xyz", end)))
        return f"{'G2' if cw else 'G3'} {' '.join(ws)} I{self.fmt(i)} J{self.fmt(j)}"

    def _inverse_time_moves(self, tp: Toolpath) -> list[str]:
        """With Z0 on the rotary centreline, the surface speed of an A move is
        r * dA; G93 lets every G1 run at its true surface feed.

        Where the machine stands at the start is unknown (after a tool change it
        is wherever the last path left it), so each axis is written the first
        time the path names it, even if the value looks unchanged."""
        out = []
        pos = {"x": None, "z": None, "a": None}
        for m in tp.moves:
            if m.y is not None:
                raise ValueError("wrapped toolpaths must not use Y")
            new = {k: getattr(m, k) if getattr(m, k) is not None else pos[k] for k in pos}
            words = [f"{k.upper()}{self.fmt(new[k])}" for k in ("x", "z", "a")
                     if getattr(m, k) is not None
                     and (pos[k] is None or abs(new[k] - pos[k]) >= 10 ** -self.decimals)]
            if words:
                if m.kind == "rapid":
                    out.append("G0 " + " ".join(words))
                else:
                    if None in pos.values():
                        raise ValueError(f"{tp.name}: feed move before X, Z and A are known")
                    r = abs(pos["z"] + new["z"]) / 2
                    dist = math.sqrt((new["x"] - pos["x"]) ** 2 + (new["z"] - pos["z"]) ** 2
                                     + (r * math.radians(new["a"] - pos["a"])) ** 2)
                    minutes = max(dist / (m.feed or 1000.0), 1e-6)
                    out.append("G1 " + " ".join(words) + f" F{self.fmt(1.0 / minutes)}")
            pos = new
        return out
